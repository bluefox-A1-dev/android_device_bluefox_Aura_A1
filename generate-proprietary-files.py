"""Inventory a complete Aura stock dump into file-level extract-utils lists."""
import argparse
from collections import defaultdict
import json
from pathlib import Path
import re
import subprocess


def generated_vendor_file(relative):
    """Keep platform build outputs out of the hardware blob inventory."""
    if relative.startswith('etc/aconfig/') or relative == 'etc/aconfig_flags.pb':
        return 'Feature flag storage generated by build/make/core/packaging/flags.mk'
    if relative in ('build.prop', 'odm/etc/build.prop', 'etc/passwd', 'etc/group',
                    'odm/etc/passwd', 'odm/etc/group'):
        return 'Build-generated properties or accounts'
    if relative in ('etc/build_flags.json', 'etc/fs_config_dirs', 'etc/fs_config_files'):
        return 'Build flags and filesystem ownership generated by the target build'
    if relative == 'etc/linker.config.pb':
        return 'Linker configuration generated from target fragments and provided libraries'
    if '/selinux/' in relative:
        return 'SELinux compiled from the target source policy'
    if relative.startswith('etc/NOTICE'):
        return 'License notices generated from the target module graph'
    return None


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('dump', type=Path)
    a = p.parse_args()
    root = Path(__file__).resolve().parent
    if not json.loads((a.dump/'extraction-status.json').read_text())['complete']:
        p.error('Only complete stock extraction is supported')
    sections = defaultdict(list)
    symlinks = []
    excluded = []
    libraries = {}
    special = []
    private_file = root/'configs/private-libraries.json'
    private = json.loads(private_file.read_text()) if private_file.is_file() else {}
    needed_fixups = {}
    text_fixups = {}
    elf_modules = {}
    renamed_file = root/'configs/renamed-binaries.json'
    renamed = json.loads(renamed_file.read_text()) if renamed_file.is_file() else {}
    config_renames = root/'configs/renamed-configs.json'
    if config_renames.is_file(): renamed.update(json.loads(config_renames.read_text()))
    source = a.dump/'vendor'
    provided_file = root/'configs/source-provided.json'
    provided = set(json.loads(provided_file.read_text())['paths']) if provided_file.is_file() else set()
    for item in sorted(source.rglob('*')):
        relative = item.relative_to(source).as_posix()
        destination = 'vendor/'+relative
        reason = generated_vendor_file(relative)
        if reason and (item.is_file() or item.is_symlink()):
            excluded.append(dict(path=destination, reason=reason))
            continue
        private_lib = item.stem in private and relative.startswith(('lib/','lib64/'))
        source_path = destination
        renamed_binary = relative in renamed
        if renamed_binary: destination = 'vendor/'+renamed[relative]
        if private_lib:
            destination = str(Path(destination).with_name(private[item.stem]+'.so'))
        if relative in provided and not private_lib and not renamed_binary:
            excluded.append(dict(path=destination,reason='Provided by the standard AOSP vendor build'))
            continue
        if item.is_symlink():
            if relative == 'lib/modules':  # Android's DLKM build creates this compatibility link.
                continue
            target = str(item.readlink())
            for old,new in renamed.items():
                if target == '/vendor/'+old: target = '/vendor/'+new
                elif Path(relative).parent.as_posix()+'/'+target == old: target = Path(new).name
            symlinks.append(dict(path=destination,target=target))
            continue
        if not item.is_file():
            continue
        flags = []
        section = 'Vendor - '+relative.split('/')[0]
        if '/vintf/' in relative:
            flags = ['EXTRACT_ONLY']
        elif item.suffix in ('.apk','.apex'):
            flags = ['EXTRACT_ONLY']
            special.append(dict(path=destination,kind='overlay' if relative.startswith('overlay/') else item.suffix[1:]))
        elif item.suffix == '.so' and relative.startswith(('lib/','lib64/')):
            flags = ['MODULE_SUFFIX=_aura_vendor']
            with item.open('rb') as f: bits = 64 if f.read(5)[4] == 2 else 32
            libraries.setdefault(Path(destination).stem,[]).append(bits)
            dynamic = subprocess.check_output(['readelf','-d',str(item)],text=True)
            soname = re.search(r'\(SONAME\).*\[(.*?)\]',dynamic)
            if private_lib or (soname and soname[1] != Path(destination).name):
                flags.append('FIX_SONAME')
        elif relative.startswith('bin/'):
            with item.open('rb') as f: elf = f.read(4) == b'\x7fELF'
            if elf:
                flags = ['MODULE_SUFFIX=_aura_vendor']
            else:
                # Shell scripts are represented by sh_binary in extract-utils.
                pass
        if item.suffix == '.so' or relative.startswith('bin/'):
            with item.open('rb') as f: is_elf = f.read(4) == b'\x7fELF'
            if is_elf:
                dynamic = subprocess.check_output(['readelf','-d',str(item)],text=True)
                needed = re.findall(r'\(NEEDED\).*\[(.*?)\]',dynamic)
                replacements = [[old+'.so',new+'.so'] for old,new in private.items() if old+'.so' in needed]
                if replacements: needed_fixups[destination] = replacements
                if relative in ('lib/mt6789/libneuron_adapter_mgvi.so', 'lib64/mt6789/libneuron_adapter_mgvi.so'):
                    # This OEM ARM ELF has a dynamic string table outside its LOAD
                    # range. readelf reads its sections; extract-utils finds no deps.
                    flags = ['EXTRACT_ONLY']
                    arch = 'android_arm64' if relative.startswith('lib64/') else 'android_arm'
                    elf_modules.setdefault('libneuron_adapter_mgvi', {})[arch] = dict(
                        srcs=['proprietary/'+destination],
                        shared_libs=[private.get(Path(n).stem, Path(n).stem) for n in needed])
        if relative.startswith('etc/') and item.stat().st_size < 1024*1024:
            try: body = item.read_text()
            except UnicodeDecodeError: body = ''
            changes = [['/vendor/'+old,'/vendor/'+new] for old,new in renamed.items() if '/vendor/'+old in body]
            if changes: text_fixups[destination] = changes
        entry_path = source_path+':'+destination if source_path != destination else destination
        line = entry_path + ''.join(';'+f for f in flags)
        sections[section].append(line)
    for partition in ('system_dlkm','vendor_dlkm','odm_dlkm'):
        for item in sorted((a.dump/partition).rglob('*')):
            if not item.is_file() or item.is_symlink():continue
            if item.name=='build.prop' or item.name.startswith('NOTICE'):continue
            # The Android module rules install KO/depmod output; keep source metadata for audit.
            sections['Kernel modules - '+partition].append(f'{partition}/{item.relative_to(a.dump/partition)};EXTRACT_ONLY')
    modules = a.dump/'vendor_boot/vendor_ramdisk00-root/lib/modules'
    for item in sorted(modules.iterdir()):
        if item.is_file():
            sections['Kernel modules - ramdisk'].append(f'prebuilt/ramdisk/modules/{item.name};EXTRACT_ONLY')
    for name,src in [('Image.lz4','boot/kernel'),('dtb.img','vendor_boot/dtb'),('dtbo.img','dtbo.img')]:
        dst = ':prebuilt/kernel/dtb/mt6789.dtb' if name=='dtb.img' else ''
        sections['Kernel and device trees'].append(f'prebuilt/kernel/{name}{dst};EXTRACT_ONLY')
    text = '# Stock BLUEFOX_J583_A8_Aura_A1_CN_V1.0.3_20260930\n'
    for name,entries in sections.items():
        text += '\n# '+name+'\n'+'\n'.join(entries)+'\n'
    (root/'proprietary-files.txt').write_text(text)
    (root/'configs').mkdir(exist_ok=True)
    (root/'configs/vendor-files.json').write_text(json.dumps(dict(libraries=libraries,special=special,symlinks=symlinks,excluded=excluded,needed_fixups=needed_fixups,text_fixups=text_fixups,elf_modules=elf_modules),indent=2)+'\n')
    # Last stock assignment wins; omit build-generated identity and ABI values.
    props = {}
    for line in (source/'build.prop').read_text().splitlines():
        if '=' in line and not line.startswith('#'):
            key,value = line.split('=',1);props[key]=value
    skip = ('ro.product.', 'ro.vendor.product.', 'ro.vendor.build.', 'ro.odm.build.', 'ro.board.', 'ro.boot.',
            'ro.virtual_ab.', 'ro.zygote', 'ro.build.', 'ro.treble.', 'ro.bionic.', 'dalvik.vm.isa.',
            'ro.minui.pixel_format', 'ro.hwui.use_vulkan')
    (root/'vendor.prop').write_text('# Hardware tuning from stock 20260930, with generated identity omitted.\n'+
        '\n'.join(k+'='+v for k,v in props.items() if not k.startswith(skip) and v)+'\n')
    print('Listed',sum(map(len,sections.values())),'files,',len(symlinks),'symlinks;',len(excluded),'generated files excluded')


if __name__ == '__main__':main()
